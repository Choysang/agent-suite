def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip() or "—"


def link(card: Card) -> str:
    return f"[[{card.path}\\|{card.id}]]"


def badge(card: Card) -> str:
    if card.kind == "lesson":
        flag = "" if card.state == "active" else f" {STATE_LABEL.get(card.state, card.state)}"
        return card.text("evidence") + flag
    return STATE_LABEL.get(card.state, "—")


def stamp(card: Card) -> str:
    return card.text("verified") or card.text("updated") or card.text("created")


def priority(card: Card) -> tuple:
    evidence = card.text("evidence")
    rank_ = EVIDENCE.index(evidence) if evidence in EVIDENCE else len(EVIDENCE)
    return list(KINDS).index(card.kind), rank_, card.id.lower()


def joined(card: Card, key: str, limit: int) -> str:
    return cell("；".join(card.items(key)[:limit]))


def table(cards: list[Card]) -> list[str]:
    if not cards:
        return ["（暂无条目）"]
    rows = ["| 条目 | 类型 | 一句话 | 何时用 | 不适用 | 证据/状态 | 日期 |", "|---|---|---|---|---|---|---|"]
    for c in sorted(cards, key=priority):
        rows.append(f"| {link(c)} | {KINDS[c.kind][1]} | {cell(c.text('summary'))} | {joined(c, 'when', 3)} "
                    f"| {joined(c, 'not_when', 2)} | {badge(c)} | {stamp(c)} |")
    return rows


def page(title: str, lines: list[str]) -> str:
    head = ["---", "kind: route", f"title: {title}", "---", "", f"# {title}", "", GENERATED, ""]
    return "\n".join(head + lines).rstrip() + "\n"


def render_domain(slug: str, spec: dict, cards: list[Card], threshold: int):
    groups = {t: [c for c in cards if f"{slug}/{t}" in c.items("tags")] for t in spec["topics"]}
    keywords = {t: "、".join(map(str, kws)) for t, kws in spec["topics"].items()}
    total = len({c.id for group in groups.values() for c in group})
    pages: dict[str, str] = {}
    if total > threshold:
        lines = ["| 主题 | 命中词 | 条目 | 三级 |", "|---|---|---|---|"]
        for t, group in groups.items():
            lines.append(f"| {t} | {cell(keywords[t])} | {len(group)} | [[{ROUTES}/{slug}/{t}\\|{t}]] |")
            pages[f"{ROUTES}/{slug}/{t}.md"] = page(f"{spec['name']} / {t}", [f"命中词：{keywords[t]}", "", *table(group)])
    else:
        lines = [line for t, group in groups.items()
                 for line in (f"## {t}", "", f"命中词：{keywords[t]}", "", *table(group), "")]
    pages[f"{ROUTES}/{slug}.md"] = page(f"{spec['name']}（{slug}）", lines)
    return pages, {t: len(group) for t, group in groups.items()}, total


def render_projects(cards: list[Card]) -> str:
    playbooks = sorted((c for c in cards if c.kind == "playbook"), key=lambda c: c.id.lower())
    if not playbooks:
        return page("项目档案总览", ["（暂无项目档案）"])
    rows = ["| 项目档案 | 一句话 | 什么样的项目会用到 | 状态 | 更新 |", "|---|---|---|---|---|"]
    rows += [f"| {link(c)} | {cell(c.text('summary'))} | {joined(c, 'when', 4)} | {badge(c)} | {stamp(c)} |"
             for c in playbooks]
    return page("项目档案总览", rows)


def render_tools(cards: list[Card]) -> str:
    tools = [c for c in cards if c.kind == "tool" and rsi.summary(c.meta, c.body)["rsi_status"] != "stale"]
    lines = ["在用：已经装好在用 ｜ 参考：记住但没装 ｜ 待评估：刚入库 ｜ 已否决：保留下来用于去重", ""]
    for state in STATE["tool"][1]:
        group = sorted((c for c in tools if c.state == state), key=lambda c: c.id.lower())
        lines += [f"## {STATE_LABEL[state]}（{len(group)}）", ""]
        if group:
            lines += ["| 工具 | 一句话 | 何时用 | 地址 |", "|---|---|---|---|"]
            lines += [f"| {link(c)} | {cell(c.text('summary'))} | {joined(c, 'when', 3)} | {c.text('url')} |"
                      for c in group]
            lines.append("")
    return page("工具库", lines)


def render_router(vault: Path, taxonomy: dict, topic_counts: dict, n_projects: int, n_tools: int) -> str:
    rows = []
    for slug, spec in taxonomy["domains"].items():
        topics = "、".join(f"{t}({topic_counts[slug][t]})" for t in spec["topics"])
        rows.append(f"| {spec['name']} | {cell('、'.join(map(str, spec['keywords'])))} | {topics} "
                    f"| `{ROUTES}/{slug}.md` | {cell(str(spec.get('redline') or ''))} |")
    kb = f'python "{vault.as_posix()}/.agents/skills/kb/scripts/kb.py" --vault "{vault.as_posix()}"'
    return ROUTER_TEMPLATE.format(vault=vault.as_posix(), kb=kb, routes=ROUTES, wiki=WIKI,
                                  rows="\n".join(rows), n_projects=n_projects, n_tools=n_tools)


def write_pages(vault: Path, pages: dict[str, str]) -> list[str]:
    for rel, text in pages.items():
        path = vault / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    keep = {(vault / rel).resolve() for rel in pages}
    root = vault / ROUTES
    removed = []
    for path in sorted(root.rglob("*.md")):
        if path.resolve() not in keep:
            path.unlink()
            removed.append(path.relative_to(vault).as_posix())
    for directory in sorted((p for p in root.rglob("*") if p.is_dir()), reverse=True):
        if not any(directory.iterdir()):
            directory.rmdir()
    return removed


def build(vault: Path, today: dt.date, write: bool = True) -> Report:
    taxonomy = load_taxonomy(vault)
    cards, errors, warnings = load(vault)
    more_errors, more_warnings = validate(cards, taxonomy, today)
    errors += more_errors
    warnings += more_warnings + broken_links(vault, cards)
    routed = [c for c in cards if c.routed]
    threshold = int(taxonomy.get("split_threshold", 40))
    pages: dict[str, str] = {}
    counts, topic_counts = {}, {}
    for slug, spec in taxonomy["domains"].items():
        domain_pages, topic_counts[slug], counts[slug] = render_domain(slug, spec, routed, threshold)
        pages.update(domain_pages)
        warnings += [f"taxonomy: 主题 {slug}/{t} 暂无条目" for t, n in topic_counts[slug].items() if n == 0]
    pages[f"{ROUTES}/projects.md"] = render_projects(routed)
    pages[f"{ROUTES}/tools.md"] = render_tools(cards)
    router = render_router(vault, taxonomy, topic_counts,
                           sum(c.kind == "playbook" for c in routed), sum(c.kind == "tool" for c in routed))
    if router.count("\n") > ROUTER_MAX_LINES:
        errors.append(f"ROUTER.md 超过 {ROUTER_MAX_LINES} 行，精简 taxonomy")
    removed: list[str] = []
    if write and not errors:
        removed = write_pages(vault, pages)
        (vault / "ROUTER.md").write_text(router, encoding="utf-8", newline="\n")
    return Report(errors, warnings, counts, removed)


# ── Find ──────────────────────────────────────────────────────────────────────

TOKEN = re.compile(r"[a-z0-9][a-z0-9_.+#-]*|[\u3400-\u9fff]+")
WEIGHTS = (("title", 3), ("summary", 3), ("when", 3), ("triggers", 3), ("tags", 2))


def tokens(text: str) -> list[str]:
    out: list[str] = []
    for run in TOKEN.findall(text.lower().replace("/", " ")):
        if run[0].isascii():
            out.append(run)
        else:  # CJK: bigrams carry far more meaning than single characters
            out += [run] if len(run) == 1 else [run[i:i + 2] for i in range(len(run) - 1)]
    return out


def card_tokens(card: Card) -> Counter:
    bag = Counter(tokens(rsi.current_body(card.body)))
    for key, weight in WEIGHTS:
        for token in tokens(" ".join(card.items(key))):
            bag[token] += weight
    return bag


def rank(cards: list[Card], query: str, k: int = 5, include_stale: bool = False) -> list[tuple[float, Card]]:
    docs = [(card, card_tokens(card)) for card in cards
            if (card.kind, card.state) not in UNROUTED and (include_stale or card.routed)]
    if not docs:
        return []
    lengths = [sum(bag.values()) for _, bag in docs]
    average = sum(lengths) / len(docs)
    df = Counter(token for _, bag in docs for token in bag)
    terms = set(tokens(query))
    results = []
    for (card, bag), length in zip(docs, lengths):
        score = sum(math.log(1 + (len(docs) - df[t] + 0.5) / (df[t] + 0.5)) * bag[t] * 2.5
                    / (bag[t] + 1.5 * (0.25 + 0.75 * length / average)) for t in terms if t in bag)
        if score > 0:
            results.append((score, card))
    def order(hit):
        score, card = hit
        signal = rsi.summary(card.meta, card.body)
        return (-score, signal["rsi_status"] != "verified", -signal["utility_score"], card.id.lower())
    return sorted(results, key=order)[:k]


def card_record(card: Card) -> dict:
    """Expose provenance and applicability without inferring evidence strength."""
    return {
        "id": card.id, "kind": card.kind, "path": f"{card.path}.md",
        "title": card.text("title"), "summary": card.text("summary"),
        "tags": card.items("tags"), "when": card.items("when"),
        "not_when": card.items("not_when"), "state": card.state,
        "evidence": card.text("evidence"), "source": card.items("source"),
        "url": card.text("url"), "created": card.text("created"),
        "verified": card.text("verified"), "updated": card.text("updated"),
        **rsi.summary(card.meta, card.body),
    }


FIND_NOTICE = "命中仅为词面相关候选；覆盖须读卡片或原文确认，无命中不等于库内无知识。"


def find_needs(cards: list[Card], query: str, needs: list[str], k: int = 5, include_stale: bool = False) -> dict:
    """Retrieve each self-contained requirement; do not claim semantic coverage."""
    requirements = []
    candidates = {}
    for index, need in enumerate(needs, 1):
        hits = rank(cards, need, k, include_stale)
        references = []
        for score, card in hits:
            record = card_record(card)
            candidates.setdefault(record["path"], record)
            references.append({"path": record["path"], "score": round(score, 2)})
        requirements.append({
            "id": f"N{index}", "query": need, "coverage": "unassessed",
            "retrieval_status": "candidates_found" if hits else "no_lexical_match",
            "hits": references,
        })
    return {"query": query, "requirements": requirements,
            "candidates": list(candidates.values()), "notice": FIND_NOTICE}


# ── Write ─────────────────────────────────────────────────────────────────────


def skeleton(kind: str, title: str, today: dt.date, **extra) -> str:
    meta: dict = {"kind": kind, "title": title, "summary": "", "tags": [], "when": [], "not_when": []}
    if kind in ("lesson", "playbook", "note", "tool"):
        meta.update(rsi_status="candidate", max_lines=60 if kind == "lesson" else 120,
                    max_chars=6000 if kind == "lesson" else 12000)
    for key in EXTRA[kind]:
        meta[key] = today if key in ("verified", "updated") else DEFAULTS.get(key, "")
    meta.update(extra)
    meta["created"] = today
    front = yaml.safe_dump(meta, allow_unicode=True, sort_keys=False, default_flow_style=None, width=1000)
    return f"---\n{front}---\n\n# {title}\n\n{BODY[kind].format(date=today.isoformat())}"


def write_card(vault: Path, kind: str, card_id: str, text: str, existing: set[str]) -> Path:
    if card_id.lower() in existing:
        raise FileExistsError(f"id 已存在：{card_id}（文件名必须全库唯一）")
    path = vault / WIKI / KINDS[kind][0] / f"{card_id}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    return path


def new_card(vault: Path, kind: str, card_id: str, today: dt.date, title: str | None = None) -> Path:
    existing = {c.id.lower() for c in load(vault)[0]}
    return write_card(vault, kind, card_id, skeleton(kind, title or card_id, today), existing)


GITHUB_REPO = re.compile(r"https://github\.com/([^/]+)/([^/]+)")


def canonical_url(url: str) -> str:
    parts = urlsplit(url.strip())
    host = parts.netloc.lower().removeprefix("www.")
    path = parts.path.rstrip("/")
    if host == "github.com":
        segments = [s for s in path.split("/") if s]
        if len(segments) < 2:
            raise ValueError(f"不是 GitHub 仓库地址：{url}")
        return f"https://github.com/{segments[0].lower()}/{segments[1].lower().removesuffix('.git')}"
    return urlunsplit(("https", host, path, parts.query, ""))


def find_by_url(cards: list[Card], url: str) -> Card | None:
    for card in cards:
        for key in ("url", "source"):
            value = card.text(key)
            try:
                if value.startswith("http") and canonical_url(value) == url:
                    return card
            except ValueError:
                continue
    return None


def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9\u3400-\u9fff]+", "-", text.lower()).strip("-")[:60] or "untitled"


def fetch_github(owner: str, repo: str) -> tuple[dict, str]:
    def get(url: str, accept: str) -> str:
        headers = {"User-Agent": "kb-intake", "Accept": accept}
        if token := os.environ.get("GITHUB_TOKEN"):
            headers["Authorization"] = f"Bearer {token}"
        with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=20) as response:
            return response.read().decode("utf-8", errors="replace")

    api = f"https://api.github.com/repos/{owner}/{repo}"
    meta = json.loads(get(api, "application/vnd.github+json"))
    try:
        readme = get(f"{api}/readme", "application/vnd.github.raw")
    except OSError:
        readme = ""
    return meta, readme


def intake(vault: Path, target: str, today: dt.date, card_id: str | None = None,
           fetch=fetch_github) -> tuple[Path, bool]:
    """target is a URL or a Web Clipper .md file (its `source` frontmatter is the URL)."""
    clip, clip_meta, url = None, {}, target
    if target.lower().endswith(".md"):
        clip = Path(target) if Path(target).is_absolute() else vault / target
        clip_meta = parse(clip.read_text(encoding="utf-8"))[0]
        url = str(clip_meta.get("source") or "")
    canonical = canonical_url(url) if url.startswith("http") else ""
    cards = load(vault)[0]
    if canonical and (existing := find_by_url(cards, canonical)):
        return vault / f"{existing.path}.md", False
    if canonical and (match := GITHUB_REPO.fullmatch(canonical)):
        meta, readme = fetch(*match.groups())
        card_id = card_id or slugify("-".join(match.groups()))
        cache = vault / INTAKE_CACHE / f"{card_id}.md"
        cache.parent.mkdir(parents=True, exist_ok=True)
        cache.write_text(readme, encoding="utf-8", newline="\n")
        extra = {"summary": meta.get("description") or "", "url": canonical, "adoption": "candidate",
                 "stars": meta.get("stargazers_count"), "license": (meta.get("license") or {}).get("spdx_id"),
                 "language": meta.get("language"), "pushed": to_date(str(meta.get("pushed_at") or "")[:10])}
        kind, title = "tool", meta.get("name") or match.group(2)
    else:
        parts = urlsplit(canonical)
        title = str(clip_meta.get("title") or "") or Path(parts.path).name or parts.netloc
        if not title:
            raise ValueError(f"剪藏没有 title 和 source：{target}")
        card_id = card_id or slugify(title)
        raw = f"{RAW_CLIPS}/{card_id}.md"
        kind = "source"
        extra = {"source": canonical or raw, "summary": str(clip_meta.get("description") or "")}
    text = skeleton(kind, title, today, **{k: v for k, v in extra.items() if v is not None})
    if clip and kind == "source":  # the clip becomes the card's L3 original
        text += f"\n## 原文\n\n[[{raw.removesuffix('.md')}]]\n"
    path = write_card(vault, kind, card_id, text, {c.id.lower() for c in cards})
    if clip and kind == "source":
        (vault / raw).parent.mkdir(parents=True, exist_ok=True)
        clip.replace(vault / raw)
    return path, True


# ── CLI ───────────────────────────────────────────────────────────────────────


def card_path(vault: Path, target: str) -> Path:
    path = (vault / target).resolve()
    root = (vault / WIKI).resolve()
    if not path.is_relative_to(root) or path.suffix != ".md":
        raise ValueError("目标必须是当前 vault 的 30.Wiki 内的 Markdown 卡片")
    if path.relative_to(root).parts[0] in NOT_CARDS:
        raise ValueError("不能把原文或生成路由当作卡片")
    return path


def read_card_file(path: Path) -> tuple[dict, str]:
    meta, body = parse(path.read_text(encoding="utf-8"))
    if meta.get("kind") not in KINDS:
        raise ValueError(f"不是有效卡片：{path}")
    return meta, body


def apply_feedback(path: Path, **kwargs) -> dict:
    lock = path.with_suffix(path.suffix + ".feedback.lock")
    try:
        fd = os.open(lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
    except FileExistsError as exc:
        raise ValueError(f"有反馈写入正在进行：{lock}；确认写入进程结束后再重试") from exc
    os.close(fd)
    temporary = None
    try:
        original = path.read_bytes()
        meta, body = parse(original.decode("utf-8"))
        if meta.get("kind") not in KINDS:
            raise ValueError("不是有效卡片")
        updated, changed = rsi.feedback(meta, body, **kwargs)
        if changed:
            newline = "\r\n" if b"\r\n" in original else "\n"
            front = yaml.safe_dump(updated, allow_unicode=True, sort_keys=False, width=1000).replace("\n", newline)
            content = f"---{newline}{front}---{newline}{body}"
            with tempfile.NamedTemporaryFile(dir=path.parent, suffix=".tmp", delete=False) as handle:
                temporary = Path(handle.name)
                handle.write(content.encode("utf-8"))
            if path.read_bytes() != original:
                raise ValueError("卡片被其他编辑者修改，停止覆盖；请重新 read")
            os.replace(temporary, path)
        return {"status": "recorded" if changed else "duplicate", "changed": changed,
                **rsi.summary(updated, body), "next_actions": ["kb build"] if changed else []}
    finally:
        if temporary and temporary.exists():
            temporary.unlink()
        lock.unlink()


def lint_path(target: Path) -> list[str]:
    if not target.exists():
        raise ValueError(f"目标不存在：{target}")
    paths = sorted(target.rglob("*.md")) if target.is_dir() else [target]
    errors = []
    checked = 0
    for path in paths:
        if any(part in NOT_CARDS or part.startswith(".") for part in path.relative_to(target.parent).parts[:-1]):
            continue
        try:
            meta, body = parse(path.read_text(encoding="utf-8"))
            if not meta.get("kind") and target.is_dir():
                continue
            checked += 1
            errors += [f"{path}: {error}" for error in rsi.lint(meta, body)]
        except (yaml.YAMLError, ValueError) as exc:
            errors.append(f"{path}: {exc}")
    if not checked and not errors:
        errors.append(f"{target}: 没有可检查的卡片")
    return errors


def default_vault() -> Path:
    return Path(os.environ.get("KB_VAULT") or Path(__file__).resolve().parents[4])


def print_report(report: Report) -> int:
    print("  ".join(f"{slug}:{n}" for slug, n in report.counts.items()))
    for path in report.removed:
        print(f"删除过期路由页 {path}")
    for warning in report.warnings:
        print(f"WARN  {warning}")
    for error in report.errors:
        print(f"ERROR {error}")
    print("OK" if not report.errors else f"{len(report.errors)} 个错误")
    return 1 if report.errors else 0


def print_hits(hits: list[tuple[float, Card]], as_json: bool) -> None:
    if as_json:
        print(json.dumps([{"score": round(s, 2), **card_record(c)} for s, c in hits],
                         ensure_ascii=False, indent=1))
        return
    for score, card in hits:
        print(f"{score:5.1f}  {KINDS[card.kind][1]}  {card.path}.md  {card.text('summary')}")
    if not hits:
        print("未找到词面匹配的候选卡片；可换同义词或查路由。")


def print_needs(report: dict, as_json: bool) -> None:
    if as_json:
        print(json.dumps(report, ensure_ascii=False, indent=1))
        return
    print(report["notice"])
    for requirement in report["requirements"]:
        print(f"\n{requirement['id']}  {requirement['query']}  [覆盖待核对]")
        for hit in requirement["hits"]:
            print(f"{hit['score']:5.1f}  {hit['path']}")
        if not requirement["hits"]:
            print("未找到词面匹配的候选卡片")


def main(argv: list[str] | None = None) -> int:
    sys.stdout.reconfigure(encoding="utf-8")  # Windows consoles default to GBK
    sys.stderr.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(prog="kb", description="第二大脑引擎")
    parser.add_argument("--vault", type=Path, default=default_vault())
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("build", help="校验并重新生成路由")
    sub.add_parser("check", help="只校验")
    find = sub.add_parser("find", help="按任务检索卡片")
    find.add_argument("query")
    find.add_argument("-k", type=int, default=5)
    find.add_argument("--need", action="append", default=[], metavar="QUERY",
                      help="完整子需求，可重复；每项独立检索，-k 对每项生效")
    find.add_argument("--json", action="store_true")
    find.add_argument("--include-stale", action="store_true", help="仅排查时读取已隔离卡片")
    read = sub.add_parser("read", help="读取当前内容，默认移除演进日志和反馈历史")
    read.add_argument("path")
    read.add_argument("--full", action="store_true")
    read.add_argument("--json", action="store_true")
    lint = sub.add_parser("lint", help="检查正文预算与治理字段；兼容旧卡片")
    lint.add_argument("path", nargs="?")
    feedback = sub.add_parser("feedback", help="对实际采用的卡片版本结算一次使用反馈")
    feedback.add_argument("path")
    feedback.add_argument("--task", required=True)
    feedback.add_argument("--revision", required=True)
    feedback.add_argument("--outcome", required=True, choices=list(rsi.OUTCOMES))
    feedback.add_argument("--reason", required=True)
    feedback.add_argument("--evidence", default="")
    feedback.add_argument("--confirm-review", action="store_true")
    new = sub.add_parser("new", help="生成卡片骨架")
    new.add_argument("kind", choices=list(KINDS))
    new.add_argument("id")
    new.add_argument("--title")
    take = sub.add_parser("intake", help="URL 或剪藏 .md 去重入库")
    take.add_argument("url", metavar="URL|CLIP.md")
    take.add_argument("--id")
    args = parser.parse_args(argv)
    if args.cmd == "find":
        if args.k < 1:
            parser.error("find -k 必须大于 0")
        if any(not tokens(need) for need in args.need):
            parser.error("--need 必须包含可检索的文字")
    vault, today = args.vault, dt.date.today()
    if args.cmd != "lint" and not (vault / TAXONOMY).exists():
        print(f"找不到 {vault / TAXONOMY}；用 --vault 或环境变量 KB_VAULT 指定 vault")
        return 2
    try:
        if args.cmd == "lint":
            errors = lint_path(vault / args.path if args.path else vault / WIKI)
            for error in errors:
                print(f"ERROR {error}", file=sys.stderr)
            print(f"{len(errors)} 个错误" if errors else "OK")
            return int(bool(errors))
        if args.cmd == "read":
            path = card_path(vault, args.path)
            meta, body = read_card_file(path)
            signal = rsi.summary(meta, body)
            if not args.full:
                meta = {key: value for key, value in meta.items() if key not in ("feedback_log", "review_revision")}
                body = rsi.current_body(body)
            if args.json:
                effective = {**meta, **{key: signal[key] for key in ("rsi_status", "utility_score", "feedback_count", "last_verified")}}
                print(json.dumps({"path": path.relative_to(vault.resolve()).as_posix(), "metadata": effective,
                                  **signal, "body": body}, ensure_ascii=False, indent=1, default=str))
            else:
                print(yaml.safe_dump({**meta, **signal}, allow_unicode=True, sort_keys=False).rstrip())
                print(body)
            return 0
        if args.cmd == "feedback":
            result = apply_feedback(card_path(vault, args.path), task=args.task, outcome=args.outcome,
                                    reason=args.reason, evidence=args.evidence, expected_revision=args.revision,
                                    today=today, confirm_review=args.confirm_review)
            print(json.dumps(result, ensure_ascii=False))
            return 0
        if args.cmd in ("build", "check"):
            return print_report(build(vault, today, write=args.cmd == "build"))
        if args.cmd == "find":
            cards, errors, warnings = load(vault)
            for warning in warnings:
                print(f"WARN  {warning}", file=sys.stderr)
            if errors:
                for error in errors:
                    print(f"ERROR {error}", file=sys.stderr)
                return 1
            if args.need:
                print_needs(find_needs(cards, args.query, args.need, args.k, args.include_stale), args.json)
            else:
                print_hits(rank(cards, args.query, args.k, args.include_stale), args.json)
        elif args.cmd == "new":
            print(new_card(vault, args.kind, args.id, today, args.title).relative_to(vault).as_posix())
        else:
            path, created = intake(vault, args.url, today, args.id)
            print(f"{'新建' if created else '已存在'} {path.relative_to(vault).as_posix()}")
    except (ValueError, OSError, yaml.YAMLError) as exc:
        print(f"失败：{exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
